//! Emits `contracts/src/stark/generated/RollupPeriodic.sol`: the Poseidon
//! round constants as periodic-column polynomials, plus the roots of unity the
//! zerofiers use. Run `zkrollup gen-sol` after changing the hash or the AIR.

use super::air::{self, Roots};
use super::field::{F, to_u256};
use ark_ff::Field;

fn hex(x: &F) -> String {
    format!("0x{:064x}", to_u256(x))
}

pub fn rollup_periodic() -> String {
    let r = Roots::get();
    let pc = air::periodic_coeffs();
    let mut s = String::new();
    s += "// SPDX-License-Identifier: MIT\n";
    s += "// GENERATED by `zkrollup gen-sol` from client/crates/zknet-core/src/stark. Do not edit.\n";
    s += "pragma solidity ^0.8.28;\n\n";
    s += "/// Roots of unity used by the rollup AIR's zerofiers (independent of T).\n";
    s += "library RollupConstants {\n";
    s += &format!("    uint256 internal constant W128_INV = {};\n", hex(&r.w128_inv));
    s += &format!("    uint256 internal constant W1024_INV = {};\n", hex(&r.w1024_inv));
    s += &format!("    uint256 internal constant W64_INV = {};\n", hex(&r.w64_inv));
    s += &format!("    uint256 internal constant W1024_63 = {};\n", hex(&r.w1024_63));
    let w8i = super::field::root(8).inverse().unwrap();
    for j in 1..4u64 {
        s += &format!("    uint256 internal constant W8_INV_{j} = {};\n", hex(&super::field::pow(w8i, j)));
    }
    s += "}\n\n";
    s += "/// The Poseidon round constants as periodic columns: c_j(x) = q_j(y) with\n";
    s += "/// y = x^(T/128) and q_j(ω_128^r) = C[r][j]. Horner over 128 coefficients.\n";
    s += "contract RollupPeriodic {\n";
    s += "    function eval(uint256 y) external pure returns (uint256 c0, uint256 c1, uint256 c2) {\n";
    s += "        assembly (\"memory-safe\") {\n";
    s += "            let p := 0x0800000000000011000000000000000000000000000000000000000000000001\n";
    for (j, name) in ["c0", "c1", "c2"].iter().enumerate() {
        let c = &pc[j];
        s += &format!("            {name} := {}\n", hex(&c[c.len() - 1]));
        for k in (0..c.len() - 1).rev() {
            s += &format!("            {name} := addmod(mulmod({name}, y, p), {}, p)\n", hex(&c[k]));
        }
    }
    s += "        }\n    }\n}\n";
    s
}

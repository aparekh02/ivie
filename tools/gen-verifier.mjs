#!/usr/bin/env node
// Generate a standalone verifier contract for one circuit from a snarkjs
// verification_key.json. The prepared VK is embedded as a bytes constant
// (lives in code: no storage reads, no registry), and verification uses the
// same audited library as the registry.
//
//   node tools/gen-verifier.mjs <vk.json> <ContractName> [out.sol]
//
// BN254 output also exposes the snarkjs ABI
//   verifyProof(uint[2] a, uint[2][2] b, uint[2] c, uint[N] pub)
// so it is a drop-in for `snarkjs zkey export solidityverifier`.
import { readFileSync, writeFileSync } from 'node:fs';
import * as zk from './zk.mjs';

const [vkPath, name, out] = process.argv.slice(2);
if (!vkPath || !name) { console.error('usage: gen-verifier.mjs <vk.json> <ContractName> [out.sol]'); process.exit(2); }
const vk = JSON.parse(readFileSync(vkPath, 'utf8'));
const c = zk.curveOf(vk.curve);
const n = vk.IC.length - 1;
if (vk.vk_gamma_2.join() === vk.vk_delta_2.join()) throw new Error('refusing: gamma == delta (zkey without a phase-2 contribution is forgeable)');
const lib = c === zk.CURVES.bn254 ? 'Groth16BN254' : 'Groth16BLS12381';

const snarkjsAbi = c === zk.CURVES.bn254 ? `
    /// snarkjs-compatible entry point. b is [[x_im, x_re], [y_im, y_re]].
    function verifyProof(uint256[2] calldata a, uint256[2][2] calldata b, uint256[2] calldata c, uint256[${n}] calldata pub)
        external view returns (bool)
    {
        bytes memory proof = abi.encodePacked(a, b[0], b[1], c);
        uint256[] memory inputs = new uint256[](${n});
        for (uint256 i = 0; i < ${n}; i++) inputs[i] = pub[i];
        return ${lib}.verify(VK, proof, inputs);
    }
` : '';

const src = `// SPDX-License-Identifier: MIT
// GENERATED by tools/gen-verifier.mjs - do not edit.
// curve: ${c.name}   public inputs: ${n}   circuitId: ${zk.circuitId(vk)}
pragma solidity ^0.8.28;

import {${lib}} from "../${lib}.sol";

contract ${name} {
    uint256 public constant N_PUBLIC = ${n};
    bytes32 public constant CIRCUIT_ID = ${zk.circuitId(vk)};
    bytes internal constant VK = hex"${zk.encodePreparedVk(vk).slice(2)}";

    function preparedVk() external pure returns (bytes memory) {
        return VK;
    }

    function verify(bytes calldata proof, uint256[] calldata inputs) external view returns (bool) {
        return ${lib}.verify(VK, proof, inputs);
    }
${snarkjsAbi}}
`;
if (out) writeFileSync(out, src); else process.stdout.write(src);
if (out) console.log(`wrote ${out} (${c.name}, ${n} public inputs)`);
